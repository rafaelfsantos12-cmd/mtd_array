let nomes = ["Pedro", "Ana", "Carlos", "Maria", "João", "Lucas", "Beatriz", "Paulo"];

console.log("Lista original:");
console.log(nomes);

nomes.sort();

console.log("Lista em ordem alfabética:");
console.log(nomes);

nomes.reverse();

console.log("Lista invertida:");
console.log(nomes);

console.log("Lista em texto:");
console.log(nomes.join(", "));